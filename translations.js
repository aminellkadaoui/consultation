export function translate(text, language) {
  if (!['dar', 'darija'].includes(language) || typeof text !== 'string') return text;
  const key = text.trim();
  if (!Object.prototype.hasOwnProperty.call(DAR, key)) return text;
  const start = text.match(/^\s*/)[0];
  const end = text.match(/\s*$/)[0];
  return start + DAR[key] + end;
}
